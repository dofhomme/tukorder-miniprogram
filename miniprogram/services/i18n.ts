/** 底栏高亮下标。商家顺序是商品、账单、开单、供应链、我的。 */
export function tabIndexFor(page: 'home' | 'products' | 'orders' | 'chain' | 'mine') {
  const path = {
    home: '/pages/home/home',
    products: '/pages/products/products',
    orders: '/pages/orders/orders',
    chain: '/pages/chain/chain',
    mine: '/pages/mine/mine',
  }[page]
  const idx = getTabItems().findIndex((item) => item.pagePath === path)
  return idx >= 0 ? idx : 0
}

export function refreshTabBarI18n() {
  const pages = getCurrentPages() || []
  for (const p of pages) {
    try {
      const bar = typeof (p as any).getTabBar === 'function' ? (p as any).getTabBar() : null
      if (bar) bar.setData({ list: getTabItems(), theme: tabBarTheme() })
    } catch (_) {}
  }
}

export function setLocale(locale: Locale) {
  if ((isGuest() || !isLoggedIn()) && !isAgentWorkspace()) return
  const next = locale === 'ug' ? 'ug' : 'zh'
  try {
    wx.setStorageSync(STORAGE_KEY, next)
  } catch (_) {}
  const apply = () => {
    const pages = getCurrentPages() || []
    for (const p of pages) {
      try {
        const page = p as { applyLocale?: () => void; setData?: (d: object) => void }
        if (typeof page.applyLocale === 'function') page.applyLocale()
        else if (typeof page.setData === 'function') page.setData(i18nState())
      } catch (_) {}
    }
    refreshTabBarI18n()
  }
  if (next === 'ug' && !ugPack) {
    void ensureUgPack().then((ok) => {
      if (!ok) {
        try {
          wx.showToast({ title: '维吾尔语还没载入，先显示中文', icon: 'none' })
        } catch (_) {}
      }
      apply()
    })
    return
  }
  apply()
}
