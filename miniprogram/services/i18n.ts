let ugPack: I18nPack | null = null
try {
  const cached = wx.getStorageSync('tuk_ug_pack_v1')
  if (cached && typeof cached === 'object') ugPack = cached as I18nPack
} catch (_) {}

function activePack(): I18nPack {
  if (getLocale() === 'ug' && ugPack) return ugPack
  return ZH
}

export function ensureUgPack(): Promise<boolean> {
  if (ugPack) return Promise.resolve(true)
  const loadUg = (require('./lazy-call.js') as { loadUg: () => Promise<I18nPack> }).loadUg
  return loadUg()
    .then((mod) => {
      const pack = ((mod as { default?: I18nPack }).default || mod) as I18nPack
      if (!pack || typeof pack !== 'object') return false
      ugPack = pack
      try {
        wx.setStorageSync('tuk_ug_pack_v1', pack)
      } catch (_) {}
      if (getLocale() === 'ug') {
        const pages = getCurrentPages() || []
        for (const p of pages) {
          try {
            const page = p as { applyLocale?: () => void; setData?: (d: object) => void }
            if (typeof page.applyLocale === 'function') page.applyLocale()
            else if (typeof page.setData === 'function') page.setData(i18nState())
          } catch (_) {}
        }
        refreshTabBarI18n()
      }
      return true
    })
    .catch(() => false)
}

export function getLocale(): Locale {
  // 游客未进代理工作台：固定中文；代理工作台 / 已登录商家可读本地语言
  if ((isGuest() || !isLoggedIn()) && !isAgentWorkspace()) return 'zh'
  try {
    const v = wx.getStorageSync(STORAGE_KEY)
    if (v === 'ug' || v === 'zh') return v
  } catch (_) {}
  return 'zh'
}

export function isRtl(): boolean {
  return getLocale() === 'ug'
}

export function t(key: string): string {
  const pack = activePack()
  // 维语包还没到时整屏用中文，避免同一屏中维混用
  return pack[key] || key
}

