import { bindPageI18n, i18nState } from '../../services/i18n'

Page({
  data: {
    title: '',
    updated: UPDATED,
    lead: '',
    sections: [] as LegalSection[],
    ...i18nState(),
  },

  _kind: 'privacy',

  applyLocale() {
    const nav =
      this._kind === 'disclaimer'
        ? 'disclaimer'
        : this._kind === 'invite'
          ? 'inviteMerchantRules'
          : 'privacy'
    bindPageI18n(this, nav)
  },

  onLoad(q: Record<string, string | undefined>) {
    const raw = String(q.type || q.kind || 'privacy')
    this._kind = raw === 'disclaimer' ? 'disclaimer' : raw === 'invite' ? 'invite' : 'privacy'
    const doc = this._kind === 'disclaimer' ? DISCLAIMER : this._kind === 'invite' ? INVITE : PRIVACY
    this.applyLocale()
    this.setData(doc)
  },

  onShow() {
    this.applyLocale()
  },
})
